#!/usr/bin/env node
/**
 * Prepares the local Langfuse stack (observability/langfuse).
 *
 * - Generates observability/langfuse/.env with fresh secrets if it is missing
 *   (never overwrites an existing one).
 * - Appends LANGFUSE_PUBLIC_KEY / LANGFUSE_SECRET_KEY / LANGFUSE_BASE_URL to
 *   apps/web/.env.local only when those keys are absent there. Other values in
 *   that file are never rewritten or printed.
 * - Prints the UI URL, the admin login and the three LANGFUSE_* values.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const langfuseDir = path.join(repoRoot, "observability", "langfuse");
const envPath = path.join(langfuseDir, ".env");
const webEnvPath = path.join(repoRoot, "apps", "web", ".env.local");

const hex = (bytes) => randomBytes(bytes).toString("hex");

function parseEnv(text) {
	const out = {};
	for (const raw of text.split(/\r?\n/)) {
		const line = raw.trim();
		if (!line || line.startsWith("#")) continue;
		const eq = line.indexOf("=");
		if (eq <= 0) continue;
		let value = line.slice(eq + 1).trim();
		if (
			(value.startsWith('"') && value.endsWith('"')) ||
			(value.startsWith("'") && value.endsWith("'"))
		) {
			value = value.slice(1, -1);
		}
		out[line.slice(0, eq).trim()] = value;
	}
	return out;
}

function generateEnv() {
	const values = {
		LANGFUSE_IMAGE_TAG: "4",
		LANGFUSE_HOST_PORT: "3100",
		MINIO_HOST_PORT: "9190",
		TELEMETRY_ENABLED: "false",
		NEXTAUTH_SECRET: hex(32),
		SALT: hex(32),
		ENCRYPTION_KEY: hex(32),
		POSTGRES_PASSWORD: hex(16),
		CLICKHOUSE_PASSWORD: hex(16),
		REDIS_AUTH: hex(16),
		MINIO_ROOT_PASSWORD: hex(16),
		LANGFUSE_INIT_PROJECT_PUBLIC_KEY: `pk-lf-${hex(16)}`,
		LANGFUSE_INIT_PROJECT_SECRET_KEY: `sk-lf-${hex(16)}`,
		LANGFUSE_INIT_USER_EMAIL: "admin@mangocut.local",
		LANGFUSE_INIT_USER_NAME: "Mangocut-Admin",
		LANGFUSE_INIT_USER_PASSWORD: hex(12),
	};
	const body = [
		"# Generated by `bun run observability:setup`. Local secrets: do not commit.",
		...Object.entries(values).map(([k, v]) => `${k}=${v}`),
		"",
	].join("\n");
	writeFileSync(envPath, body, { mode: 0o600 });
	return values;
}

let env;
if (existsSync(envPath)) {
	env = parseEnv(readFileSync(envPath, "utf8"));
	console.log(`Using existing ${path.relative(repoRoot, envPath)}`);
} else {
	env = generateEnv();
	console.log(`Generated ${path.relative(repoRoot, envPath)} with fresh secrets`);
}

const port = env.LANGFUSE_HOST_PORT || "3100";
const baseUrl = `http://127.0.0.1:${port}`;
const webVars = {
	LANGFUSE_PUBLIC_KEY: env.LANGFUSE_INIT_PROJECT_PUBLIC_KEY,
	LANGFUSE_SECRET_KEY: env.LANGFUSE_INIT_PROJECT_SECRET_KEY,
	LANGFUSE_BASE_URL: baseUrl,
};

const webText = existsSync(webEnvPath) ? readFileSync(webEnvPath, "utf8") : "";
const existingWeb = parseEnv(webText);
// A key counts as set only with a non-empty value: `.env.example` ships the
// LANGFUSE_* keys blank, and a copied example must still get them filled in.
const blank = Object.entries(webVars).filter(
	([k]) => k in existingWeb && !existingWeb[k],
);
const absent = Object.entries(webVars).filter(([k]) => !(k in existingWeb));
if (blank.length > 0 || absent.length > 0) {
	let next = webText;
	for (const [k, v] of blank) {
		next = next.replace(new RegExp(`^(${k})=\\s*$`, "m"), `$1=${v}`);
	}
	if (absent.length > 0) {
		const prefix = next && !next.endsWith("\n") ? "\n" : "";
		next += `${prefix}\n# Local Langfuse tracing (observability/README.md)\n${absent
			.map(([k, v]) => `${k}=${v}`)
			.join("\n")}\n`;
	}
	writeFileSync(webEnvPath, next);
	console.log(
		`Set ${[...blank, ...absent].map(([k]) => k).join(", ")} in ${path.relative(repoRoot, webEnvPath)}`,
	);
} else {
	console.log(
		`${path.relative(repoRoot, webEnvPath)} already defines the LANGFUSE_* keys; left unchanged`,
	);
}

console.log(`
Langfuse UI:   http://localhost:${port}
Admin login:   ${env.LANGFUSE_INIT_USER_EMAIL} / ${env.LANGFUSE_INIT_USER_PASSWORD}

Tracing env (apps/web/.env.local):
LANGFUSE_PUBLIC_KEY=${webVars.LANGFUSE_PUBLIC_KEY}
LANGFUSE_SECRET_KEY=${webVars.LANGFUSE_SECRET_KEY}
LANGFUSE_BASE_URL=${webVars.LANGFUSE_BASE_URL}

Next: bun run observability:up`);
